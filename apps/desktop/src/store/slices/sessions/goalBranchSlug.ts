type Params = {
  readonly text: string;
  readonly maxLength: number;
};

type TokenParams = {
  readonly token: string;
};

const wordsOfToken = ({ token }: TokenParams): ReadonlyArray<string> =>
  TICKET.test(token) ? [token] : token.split('-');

const isMeaningful = ({ token }: TokenParams): boolean => token !== '' && !STOPWORDS.has(token);

export const goalBranchSlug = ({ text, maxLength }: Params): string => {
  const tokens = text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .split(/[^a-z0-9-]+/)
    .flatMap((token) => wordsOfToken({ token }))
    .filter((token) => isMeaningful({ token }));
  const tickets = tokens.filter((token) => TICKET.test(token));
  const words = [...new Set([...tickets, ...tokens])].slice(0, MAX_WORDS);
  const first = words[0];
  if (first === undefined) {
    return '';
  }
  if (first.length > maxLength) {
    return first.slice(0, maxLength);
  }
  let slug = first;
  for (const word of words.slice(1)) {
    const next = `${slug}-${word}`;
    if (next.length > maxLength) {
      break;
    }
    slug = next;
  }
  return slug;
};

import { inlineMarkdownText } from '@goodboy/ui';

const HTML_COMMENT_OPEN = '<!--';
const HTML_COMMENT_CLOSE = '-->';
const HTML_TAG = /<\/?[a-z][^<>\n]{0,200}>/gi;
const IMAGE = /!\[[^\]\n]{0,120}\]\([^)\n]{0,400}\)/g;
const RULE_LINE = /^[-*_=\s]{3,}$/;
const LEADING_MARKER = /^(?:#{1,6}\s+|>\s*|[-*+]\s+)+/;
const SEVERITY_SPLIT = /[|,·:]/;
const SEVERITY_WORDS: ReadonlySet<string> = new Set([
  'low',
  'medium',
  'high',
  'critical',
  'major',
  'minor',
  'nitpick',
  'trivial',
  'potential issue',
  'suggestion',
  'refactor',
  'severity',
  'priority',
]);
const BOILERPLATE_PREFIXES: ReadonlyArray<string> = [
  'powered by',
  'reply with',
  'was this helpful',
  'prompt for ai',
  'prompt for all review',
  'learnt from',
  'learnings used',
  'generated by',
  'this is an auto',
  'summary by',
  'walkthrough',
];

type TextParams = {
  readonly text: string;
};

const withoutHtmlComments = ({ text }: TextParams): string => {
  let rest = text;
  let out = '';
  while (true) {
    const open = rest.indexOf(HTML_COMMENT_OPEN);
    if (open < 0) {
      return out + rest;
    }
    const close = rest.indexOf(HTML_COMMENT_CLOSE, open + HTML_COMMENT_OPEN.length);
    out += rest.slice(0, open);
    if (close < 0) {
      return out;
    }
    rest = rest.slice(close + HTML_COMMENT_CLOSE.length);
  }
};

const wordOf = ({ text }: TextParams): string =>
  text
    .replace(/[^a-z ]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

const isSeverityLine = ({ text }: TextParams): boolean => {
  const parts = text
    .split(SEVERITY_SPLIT)
    .map((part) => wordOf({ text: part }))
    .filter((part) => part.length > 0);
  return parts.length > 0 && parts.every((part) => SEVERITY_WORDS.has(part));
};

const isBoilerplateLine = ({ text }: TextParams): boolean => {
  const lower = text.toLowerCase();
  return BOILERPLATE_PREFIXES.some((prefix) => lower.startsWith(prefix));
};

const cleanLineOf = ({ text }: TextParams): string =>
  text
    .replace(IMAGE, ' ')
    .replace(HTML_TAG, ' ')
    .trim()
    .replace(LEADING_MARKER, '')
    .replace(/\s+/g, ' ')
    .trim();

export const commentPreviewOf = ({ text }: TextParams): string => {
  const lines = withoutHtmlComments({ text }).split('\n');
  for (const raw of lines) {
    const line = cleanLineOf({ text: raw });
    if (line.length === 0 || RULE_LINE.test(line)) {
      continue;
    }
    if (isSeverityLine({ text: line }) || isBoilerplateLine({ text: line })) {
      continue;
    }
    const plain = inlineMarkdownText({ text: line }).trim();
    if (plain.length > 0) {
      return plain;
    }
  }
  return '';
};
